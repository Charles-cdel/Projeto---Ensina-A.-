-- ENSINA AÍ | Modelo inicial do CRM escolar (PostgreSQL/Supabase)
-- 10 tabelas de aplicação + auth.users (gerenciado pelo Supabase Auth).
-- Execute na ordem das migrations. Não armazene segredos no repositório.

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null check (length(btrim(nome)) >= 2),
  papel text not null check (papel in ('gestor', 'atendente')),
  ativo boolean not null default true,
  disponivel boolean not null default false,
  ultima_atribuicao_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table public.series_escolares (
  id smallint generated by default as identity primary key,
  nome text not null unique,
  nivel text not null check (nivel in ('educacao_infantil', 'fundamental_i', 'fundamental_ii', 'ensino_medio')),
  ordem smallint not null unique check (ordem > 0),
  ativo boolean not null default true
);

create table public.turnos (
  id smallint generated by default as identity primary key,
  nome text not null unique,
  ativo boolean not null default true
);

-- Dados institucionais alimentados pela escola; não cadastrar informações inventadas.
create table public.informacoes_escola (
  id boolean primary key default true check (id = true),
  nome text,
  descricao text,
  endereco text,
  telefone text,
  whatsapp text,
  email text,
  site text,
  horario_atendimento text,
  atualizado_em timestamptz not null default now()
);

create table public.leads (
  id uuid primary key default gen_random_uuid(),
  nome_responsavel text not null check (length(btrim(nome_responsavel)) >= 2),
  telefone text not null check (length(btrim(telefone)) >= 8),
  email text,
  nome_aluno text,
  idade_aluno smallint check (idade_aluno between 1 and 30),
  serie_interesse_id smallint references public.series_escolares(id) on delete set null,
  turno_interesse_id smallint references public.turnos(id) on delete set null,
  canal text not null check (canal in ('whatsapp', 'instagram', 'site', 'presencial', 'outro')),
  mensagem_inicial text,
  consentimento_contato boolean not null default false,
  consentimento_em timestamptz,
  criado_por uuid references public.perfis(id) on delete set null default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint consentimento_coerente check (not consentimento_contato or consentimento_em is not null)
);

-- 1 lead = 1 atendimento na fase inicial do CRM.
create table public.atendimentos (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid not null unique references public.leads(id) on delete restrict,
  atendente_id uuid references public.perfis(id) on delete set null,
  status text not null default 'novo' check (
    status in ('aguardando_atribuicao', 'novo', 'em_contato',
               'aguardando_retorno', 'visita_agendada', 'concluido', 'perdido')
  ),
  observacoes text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table public.interacoes (
  id uuid primary key default gen_random_uuid(),
  atendimento_id uuid not null references public.atendimentos(id) on delete cascade,
  autor_id uuid references public.perfis(id) on delete set null default auth.uid(),
  canal text not null check (canal in ('whatsapp', 'telefone', 'email', 'presencial', 'chat_ia', 'outro')),
  direcao text not null check (direcao in ('entrada', 'saida', 'interna')),
  tipo text not null check (tipo in ('mensagem', 'ligacao', 'nota', 'automacao')),
  conteudo text not null check (length(btrim(conteudo)) > 0),
  criado_em timestamptz not null default now()
);

create table public.historico_atribuicoes (
  id uuid primary key default gen_random_uuid(),
  atendimento_id uuid not null references public.atendimentos(id) on delete cascade,
  atendente_anterior_id uuid references public.perfis(id) on delete set null,
  atendente_novo_id uuid references public.perfis(id) on delete set null,
  alterado_por uuid references public.perfis(id) on delete set null,
  tipo text not null check (tipo in ('automatica', 'manual')),
  motivo text,
  criado_em timestamptz not null default now()
);

create table public.visitas (
  id uuid primary key default gen_random_uuid(),
  atendimento_id uuid not null references public.atendimentos(id) on delete cascade,
  agendada_para timestamptz not null,
  status text not null default 'agendada' check (
    status in ('agendada', 'realizada', 'cancelada', 'nao_compareceu')
  ),
  observacoes text,
  criada_por uuid references public.perfis(id) on delete set null default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create table public.tarefas (
  id uuid primary key default gen_random_uuid(),
  atendimento_id uuid not null references public.atendimentos(id) on delete cascade,
  responsavel_id uuid references public.perfis(id) on delete set null default auth.uid(),
  titulo text not null check (length(btrim(titulo)) > 0),
  descricao text,
  vencimento_em timestamptz,
  status text not null default 'pendente' check (status in ('pendente', 'concluida', 'cancelada')),
  criada_por uuid references public.perfis(id) on delete set null default auth.uid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);

create index perfis_distribuicao_idx on public.perfis (papel, ativo, disponivel, ultima_atribuicao_em);
create index leads_criados_idx on public.leads (criado_em desc);
create index leads_serie_idx on public.leads (serie_interesse_id);
create index atendimentos_fila_idx on public.atendimentos (atendente_id, status);
create index atendimentos_criados_idx on public.atendimentos (criado_em desc);
create index interacoes_atendimento_data_idx on public.interacoes (atendimento_id, criado_em desc);
create index historico_atendimento_data_idx on public.historico_atribuicoes (atendimento_id, criado_em desc);
create index visitas_atendimento_data_idx on public.visitas (atendimento_id, agendada_para);
create index tarefas_responsavel_status_idx on public.tarefas (responsavel_id, status, vencimento_em);
create index tarefas_atendimento_idx on public.tarefas (atendimento_id);

create function private.atualizar_data()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;

create trigger perfis_atualizado before update on public.perfis
  for each row execute function private.atualizar_data();
create trigger escola_atualizada before update on public.informacoes_escola
  for each row execute function private.atualizar_data();
create trigger leads_atualizado before update on public.leads
  for each row execute function private.atualizar_data();
create trigger atendimentos_atualizado before update on public.atendimentos
  for each row execute function private.atualizar_data();
create trigger visitas_atualizada before update on public.visitas
  for each row execute function private.atualizar_data();
create trigger tarefas_atualizada before update on public.tarefas
  for each row execute function private.atualizar_data();

-- Segurança por padrão mesmo se a configuração da Data API habilitar grants amplos.
alter table public.perfis enable row level security;
alter table public.series_escolares enable row level security;
alter table public.turnos enable row level security;
alter table public.informacoes_escola enable row level security;
alter table public.leads enable row level security;
alter table public.atendimentos enable row level security;
alter table public.interacoes enable row level security;
alter table public.historico_atribuicoes enable row level security;
alter table public.visitas enable row level security;
alter table public.tarefas enable row level security;

revoke all on public.perfis, public.series_escolares, public.turnos,
  public.informacoes_escola, public.leads, public.atendimentos,
  public.interacoes, public.historico_atribuicoes, public.visitas,
  public.tarefas from anon, authenticated;

-- Sem INSERT/UPDATE direto no histórico; ele é preenchido por gatilhos internos.
-- Sem DELETE para usuários do app; exclusão/retencao exigem fluxo administrativo.
grant select on public.perfis, public.series_escolares, public.turnos,
  public.informacoes_escola, public.leads, public.atendimentos,
  public.interacoes, public.historico_atribuicoes, public.visitas,
  public.tarefas to authenticated;
grant update (nome, disponivel) on public.perfis to authenticated;
grant insert, update on public.series_escolares, public.turnos, public.informacoes_escola to authenticated;
grant insert on public.leads, public.interacoes, public.visitas, public.tarefas to authenticated;
grant update (nome_responsavel, telefone, email, nome_aluno, idade_aluno,
  serie_interesse_id, turno_interesse_id, mensagem_inicial, consentimento_contato,
  consentimento_em) on public.leads to authenticated;
grant update (atendente_id, status, observacoes) on public.atendimentos to authenticated;
grant update (agendada_para, status, observacoes) on public.visitas to authenticated;
grant update (responsavel_id, titulo, descricao, vencimento_em, status) on public.tarefas to authenticated;
-- Identity sequences do not require broad grants on unrelated public sequences.

revoke execute on function private.atualizar_data() from public, anon, authenticated;
